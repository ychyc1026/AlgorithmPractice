/*
题目：有100个石头，每次可以取1，3，4，6个，先取100者胜，问为了赢应先手还是后手
*/
#include <bits/stdc++.h>
using namespace std;



//思考1：
//分析：
//必胜态 N ，存在取一步就留下P的局面（有策略到P局面）
//必败态 P ，怎么取都留下N局面
//1 3 4 6取则胜
//f[1] 3 4 6是1，N
//如果f[i] 取1 3 4 6都没有得到P，说明：所有能走的下一步都落到 N 态，没有一个落到 P 态（不一定是被1 3 4 6一次取完，因为递推状态来自前一个，都用前一个状态表示，不一定是最后一步取），操作f[i-1] f[i-3] f[i-4] f[i-6] 都不能得到P
//那么它就是P：当 f[i-1] && f[i-3] && f[i-4] && f[i-6] == 1 时，f[i] = 0
//初始f[]里面都装0（从7）开始
//f[i]=!(f[i-1]&&f[i-3]&&f[i-4]&&f[i-6])集合固定时，把内层循环展开成布尔表达式

#define MAX 101
int f[MAX];
//输入n，可以是100，也可以是其它数
int game(int n){
    //返回1表示先取会胜，0表示先取会输
    //f[i]是表示还剩i个，值是还剩i个的状态是1 还是 0，是1先手胜，N，是0先手败，P
    f[0]=0;
    f[1]=1;
    f[2]=0;
    f[3]=1;
    f[4]=1;
    f[5]=1;
    f[6]=1;
    /*
    最大取法是 6
    公式里有 f[i-6]，这个下标要合法
    */
    for(int i=7;i<=n;i++){
        f[i]=!(f[i-1]&&f[i-3]&&f[i-4]&&f[i-6]);//后面的f[i]需要前面的f[i]
    }
    return f[n];
}


//思考2：
//这种思路的减法游戏通解：
int S[] = {1,3,4,6};          // ← 换题只改这里
int K = 4;
int game(int n) {
    vector<int> f(n + 1, 0);            // 长度 n+1，下标 0..n 都合法
    for (int i = 1; i <= n; ++i)
        for (int j = 0; j < K; ++j) {
            int s = S[j];
            if (s <= i && f[i - s] == 0) {   // 能一步走到 P
                f[i] = 1;                    //f[]里面都是0，找到解法就改成1，不然还是0
                break;                       // 找到一个就够了
            }
        }
    return f[n];
}


//思考3：
//特殊情况打表找规律：
//P的位置：间隔2，5，2，5，2，5，2......
//周期是7
/*
必败条件是 n % 7 == 0 || n % 7 == 2。于是可以绕过 DP，直接 O(1)：
n=100，100%7=2 → 先手必败。和 DP 结果对得上，周期假设验证通过。
注意：这一步是"打表之后找规律"，不是巴什博弈的 n%(m+1)。因为 {1,3,4,6} 不连续，凑不出固定和，周期 7 是这道题特有的，换个集合就得重新打表找。

*/
bool firstWin(int n) {
    return !(n % 7 == 0 || n % 7 == 2);
}

//思考4：补一个递归：(轮到的人胜负1 0)
//题目有变，是取1 或2个石头，便于观看
//前提条件：n=0是P态，我取1 2 后状态是P态，我是N态（1）;
int game(int n){
    if(n==0) return 0;
    if((n-1)>=0&&game(n-1)==0) return 1;
    if((n-2)>=0&&game(n-2)==0) return 1;
    return 0;

}


//思考5：优化递归
int memo[105];      // 本子：memo[n] 存 game(n) 的答案
bool visited[105];  // 标记：visited[n] 表示"n 这页记过没有"

int game(int n) {
    if (n == 0) return 0;

    if (visited[n]) return memo[n];   // 记过？直接抄，不再往下问

    visited[n] = true;                // 先登记"我要算 n 了"

    if (n >= 1 && game(n - 1) == 0) return memo[n] = 1;
    if (n >= 2 && game(n - 2) == 0) return memo[n] = 1;
    return memo[n] = 0;
}